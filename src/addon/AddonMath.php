declare(strict_types=1);

namespace pocketmine\addon;

use function mt_getrandmax;
use function mt_rand;

/**
 * Small numeric helpers for the add-on runtime.
 */
final class AddonMath{

	private function __construct(){
		//NOOP
	}

	/** A uniformly distributed float in [0, 1). (lcg_value() is deprecated as of PHP 8.4.) */
	public static function randomFloat() : float{
		return mt_rand() / (mt_getrandmax() + 1);
	}
}

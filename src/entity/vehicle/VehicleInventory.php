namespace pocketmine\entity\vehicle;

use pocketmine\inventory\SimpleInventory;

class VehicleInventory extends SimpleInventory{

	public function __construct(
		protected Vehicle $holder,
		int $size = 27
	){
		parent::__construct($size);
	}

	public function getHolder() : Vehicle{
		return $this->holder;
	}
}
